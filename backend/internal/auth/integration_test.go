var codePattern = regexp.MustCompile(`\b(\d{6})\b`)

type apiEnvelope[T any] struct {
	Code    int    `json:"code"`
	Message string `json:"message"`
	Data    T      `json:"data"`
}

type authResponseData struct {
	Token string `json:"token"`
	User  struct {
		ID       int64  `json:"id"`
		Email    string `json:"email"`
		Nickname string `json:"nickname"`
	} `json:"user"`
}

type meResponseData struct {
	ID       int64  `json:"id"`
	Email    string `json:"email"`
	Nickname string `json:"nickname"`
}

type expireResponseData struct {
	ExpireSeconds int `json:"expireSeconds"`
}

type integrationSender struct {
	mu       sync.Mutex
	messages []mail.Message
}

func (s *integrationSender) Send(_ context.Context, message mail.Message) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	s.messages = append(s.messages, message)
	return nil
}

func (s *integrationSender) LatestCode(t *testing.T, to string, subjectContains string) string {
	t.Helper()

	s.mu.Lock()
	defer s.mu.Unlock()

	for i := len(s.messages) - 1; i >= 0; i-- {
		message := s.messages[i]
		if message.To != to {
			continue
		}
		if subjectContains != "" && !strings.Contains(message.Subject, subjectContains) {
			continue
		}

		matches := codePattern.FindStringSubmatch(message.Text)
		if len(matches) == 2 {
			return matches[1]
		}
	}

	t.Fatalf("no verification code found for %q with subject containing %q", to, subjectContains)
	return ""
}

