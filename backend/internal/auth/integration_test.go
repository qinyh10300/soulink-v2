func TestAuthIntegration_RegisterLoginChangePasswordLogoutLifecycle(t *testing.T) {
	if os.Getenv(runIntegrationEnv) != "1" {
		t.Skipf("set %s=1 to run auth integration tests", runIntegrationEnv)
	}

	env := newIntegrationEnv(t)

	email := fmt.Sprintf("auth-it-%d@mails.tsinghua.edu.cn", time.Now().UnixNano())
	initialPassword := "Start1234"
	newPassword := "Change5678"

	status, registerCodeResp := doJSON[expireResponseData](t, env, http.MethodPost, "/api/v1/auth/register/send-code", "", map[string]string{
		"email": email,
	})
	if status != http.StatusOK {
		t.Fatalf("register/send-code status = %d, want %d", status, http.StatusOK)
	}
	if registerCodeResp.Data.ExpireSeconds <= 0 {
		t.Fatalf("register/send-code expireSeconds = %d, want > 0", registerCodeResp.Data.ExpireSeconds)
	}

	registerCode := env.sender.LatestCode(t, email, "\u6ce8\u518c\u9a8c\u8bc1\u7801")

	status, registerResp := doJSON[authResponseData](t, env, http.MethodPost, "/api/v1/auth/register", "", map[string]string{
		"email":      email,
		"code":       registerCode,
		"password":   initialPassword,
		"nickname":   "integration-user",
		"department": "computer-school",
		"grade":      "grade-3",
	})
	if status != http.StatusOK {
		t.Fatalf("register status = %d, want %d", status, http.StatusOK)
	}
	registerToken := registerResp.Data.Token
	if registerToken == "" {
		t.Fatal("register token is empty")
	}
	if registerResp.Data.User.Email != email {
		t.Fatalf("register user email = %q, want %q", registerResp.Data.User.Email, email)
	}

	status, meResp := doJSON[meResponseData](t, env, http.MethodGet, "/api/v1/auth/me", registerToken, nil)
	if status != http.StatusOK {
		t.Fatalf("me after register status = %d, want %d", status, http.StatusOK)
	}
	if meResp.Data.Email != email {
		t.Fatalf("me after register email = %q, want %q", meResp.Data.Email, email)
	}

	status, logoutRegisterResp := doJSON[map[string]any](t, env, http.MethodPost, "/api/v1/auth/logout", registerToken, nil)
	if status != http.StatusOK {
		t.Fatalf("logout after register status = %d, want %d", status, http.StatusOK)
	}
	if logoutRegisterResp.Message != "logout success" {
		t.Fatalf("logout after register message = %q, want %q", logoutRegisterResp.Message, "logout success")
	}

	status, loggedOutMeResp := doJSON[map[string]any](t, env, http.MethodGet, "/api/v1/auth/me", registerToken, nil)
	if status != http.StatusUnauthorized {
		t.Fatalf("me after register logout status = %d, want %d", status, http.StatusUnauthorized)
	}
	if loggedOutMeResp.Code != httpapi.CodeInvalidToken {
		t.Fatalf("me after register logout code = %d, want %d", loggedOutMeResp.Code, httpapi.CodeInvalidToken)
	}

	status, loginResp := doJSON[authResponseData](t, env, http.MethodPost, "/api/v1/auth/login", "", map[string]string{
		"email":    email,
		"password": initialPassword,
	})
	if status != http.StatusOK {
		t.Fatalf("login with initial password status = %d, want %d", status, http.StatusOK)
	}
	loginToken := loginResp.Data.Token
	if loginToken == "" {
		t.Fatal("login token is empty")
	}

	status, changeCodeResp := doJSON[map[string]any](t, env, http.MethodPost, "/api/v1/users/me/password/send-code", loginToken, nil)
	if status != http.StatusOK {
		t.Fatalf("password/send-code status = %d, want %d", status, http.StatusOK)
	}
	if changeCodeResp.Message != "verification code sent" {
		t.Fatalf("password/send-code message = %q, want %q", changeCodeResp.Message, "verification code sent")
	}

	changeCode := env.sender.LatestCode(t, email, "\u4fee\u6539\u5bc6\u7801\u9a8c\u8bc1\u7801")

	status, changePasswordResp := doJSON[map[string]any](t, env, http.MethodPost, "/api/v1/users/me/password", loginToken, map[string]string{
		"code":        changeCode,
		"newPassword": newPassword,
	})
	if status != http.StatusOK {
		t.Fatalf("change password status = %d, want %d", status, http.StatusOK)
	}
	if changePasswordResp.Message != "password updated" {
		t.Fatalf("change password message = %q, want %q", changePasswordResp.Message, "password updated")
	}

	status, revokedSessionResp := doJSON[map[string]any](t, env, http.MethodGet, "/api/v1/auth/me", loginToken, nil)
	if status != http.StatusUnauthorized {
		t.Fatalf("me after password change status = %d, want %d", status, http.StatusUnauthorized)
	}
	if revokedSessionResp.Code != httpapi.CodeInvalidToken {
		t.Fatalf("me after password change code = %d, want %d", revokedSessionResp.Code, httpapi.CodeInvalidToken)
	}

	status, oldPasswordLoginResp := doJSON[map[string]any](t, env, http.MethodPost, "/api/v1/auth/login", "", map[string]string{
		"email":    email,
		"password": initialPassword,
	})
	if status != http.StatusUnauthorized {
		t.Fatalf("login with old password status = %d, want %d", status, http.StatusUnauthorized)
	}
	if oldPasswordLoginResp.Code != httpapi.CodeInvalidCredentials {
		t.Fatalf("login with old password code = %d, want %d", oldPasswordLoginResp.Code, httpapi.CodeInvalidCredentials)
	}

	status, reloginResp := doJSON[authResponseData](t, env, http.MethodPost, "/api/v1/auth/login", "", map[string]string{
		"email":    email,
		"password": newPassword,
	})
	if status != http.StatusOK {
		t.Fatalf("login with new password status = %d, want %d", status, http.StatusOK)
	}
	reloginToken := reloginResp.Data.Token
	if reloginToken == "" {
		t.Fatal("relogin token is empty")
	}

	status, finalLogoutResp := doJSON[map[string]any](t, env, http.MethodPost, "/api/v1/auth/logout", reloginToken, nil)
	if status != http.StatusOK {
		t.Fatalf("final logout status = %d, want %d", status, http.StatusOK)
	}
	if finalLogoutResp.Message != "logout success" {
		t.Fatalf("final logout message = %q, want %q", finalLogoutResp.Message, "logout success")
	}

	status, finalMeResp := doJSON[map[string]any](t, env, http.MethodGet, "/api/v1/auth/me", reloginToken, nil)
	if status != http.StatusUnauthorized {
		t.Fatalf("me after final logout status = %d, want %d", status, http.StatusUnauthorized)
	}
	if finalMeResp.Code != httpapi.CodeInvalidToken {
		t.Fatalf("me after final logout code = %d, want %d", finalMeResp.Code, httpapi.CodeInvalidToken)
	}
}

func newIntegrationEnv(t *testing.T) *integrationEnv {
	t.Helper()

	baseDSN := integrationBaseDSN(t)
	ctx := context.Background()

	adminDB, err := database.Open(ctx, config.DatabaseConfig{DSN: baseDSN})
	if err != nil {
		t.Fatalf("open integration admin database: %v", err)
	}

	dbName := fmt.Sprintf("soulink_auth_it_%d", time.Now().UnixNano())
	if _, err := adminDB.ExecContext(ctx, fmt.Sprintf(`CREATE DATABASE "%s"`, dbName)); err != nil {
		_ = adminDB.Close()
		t.Fatalf("create integration database %q: %v", dbName, err)
	}

	testDSN := replaceDatabaseName(t, baseDSN, dbName)
	db, err := database.Open(ctx, config.DatabaseConfig{DSN: testDSN})
	if err != nil {
		_ = dropIntegrationDatabase(context.Background(), adminDB, dbName)
		_ = adminDB.Close()
		t.Fatalf("open integration test database: %v", err)
	}

	if err := migrate.Up(ctx, db); err != nil {
		_ = db.Close()
		_ = dropIntegrationDatabase(context.Background(), adminDB, dbName)
		_ = adminDB.Close()
		t.Fatalf("run integration migrations: %v", err)
	}

	logger := slog.New(slog.NewTextHandler(io.Discard, nil))
	dataStore := store.New(db)
	sender := &integrationSender{}
	tokenManager := auth.NewTokenManager("integration-secret", time.Hour)
	authService := auth.NewService(dataStore, sender, tokenManager, logger, config.AuthConfig{
		JWTSecret:                "integration-secret",
		JWTTTL:                   time.Hour,
		VerificationCodeTTL:      5 * time.Minute,
		VerificationCodeCooldown: time.Second,
		BCryptCost:               bcrypt.MinCost,
	})

	router := app.NewRouter(app.Dependencies{
		Logger:               logger,
		AllowedOrigins:       []string{"http://localhost:5173"},
		AuthMiddleware:       auth.Middleware(dataStore, tokenManager),
		AuthHandler:          auth.NewHandler(authService),
		ProfileHandler:       profile.NewHandler(profile.NewService(dataStore)),
		MetaHandler:          meta.NewHandler(meta.NewService()),
		QuestionnaireHandler: questionnaire.NewHandler(),
		MatchHandler:         match.NewHandler(),
	})

	server := httptest.NewServer(router)

	env := &integrationEnv{
		server:  server,
		client:  server.Client(),
		adminDB: adminDB,
		db:      db,
		dbName:  dbName,
		sender:  sender,
	}

	t.Cleanup(func() {
		server.Close()
		_ = db.Close()
		_ = dropIntegrationDatabase(context.Background(), adminDB, dbName)
		_ = adminDB.Close()
	})

	return env
}

func doJSON[T any](t *testing.T, env *integrationEnv, method, path, token string, body any) (int, apiEnvelope[T]) {
	t.Helper()

	var bodyReader io.Reader
	if body != nil {
		payload, err := json.Marshal(body)
		if err != nil {
			t.Fatalf("marshal request body: %v", err)
		}
		bodyReader = bytes.NewReader(payload)
	}

	req, err := http.NewRequest(method, env.server.URL+path, bodyReader)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}

	resp, err := env.client.Do(req)
	if err != nil {
		t.Fatalf("perform request %s %s: %v", method, path, err)
	}
	defer resp.Body.Close()

	rawBody, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("read response body: %v", err)
	}

	var envelope apiEnvelope[T]
	if err := json.Unmarshal(rawBody, &envelope); err != nil {
		t.Fatalf("decode response body %q: %v", string(rawBody), err)
	}

	return resp.StatusCode, envelope
}

